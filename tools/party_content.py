def iter_cards():
    """Yield (kind, age, text) for every curated card."""
    for kind, blob in CARDS.items():
        for line in blob.split("\n"):
            line = line.strip()
            if not line or "|" not in line:
                continue
            age_raw, text = line.split("|", 1)
            text = text.strip()
            try:
                age = int(age_raw)
            except ValueError:
                continue
            if age not in AGE_ORDER:
                continue
            if len(text) < 4:
                continue
            yield kind, age, text


def stats():
    from collections import Counter
    c = Counter()
    a = Counter()
    for kind, age, _t in iter_cards():
        c[kind] += 1
        a[(kind, age)] += 1
    return {"by_kind": dict(c.most_common()),
            "by_kind_age": {f"{k}:{ag}": v for (k, ag), v in sorted(a.items())},
            "total": sum(c.values())}


