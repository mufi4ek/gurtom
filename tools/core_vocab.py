VALID_WORD_RE = re.compile(r"^[а-яіїєґ'’\-]{2,40}$", re.I)
PHRASE_WORD_RE = re.compile(r"^[а-яіїєґ'’\-]+(?: [а-яіїєґ'’\-]+){1,7}$", re.I)


def iter_core():
    """Yield (topic, age, difficulty, word) for every curated occurrence.

    A word may appear in several topics (смачний -> food AND traits); all
    occurrences are yielded so the builder can attach every topic.

    The "idioms" block is split by NEWLINE (one idiom per line); every other
    block is a plain whitespace-separated word list.  Latin-script typos are
    filtered out by the validity regexes.
    """
    for topic, blocks in CORE.items():
        for age, diff, text in blocks:
            if topic == "idioms":
                items = [" ".join(line.split()) for line in text.split("\n")]
                rx = PHRASE_WORD_RE
            else:
                items = text.split()
                rx = VALID_WORD_RE
            for raw in items:
                w = raw.strip().lower().replace("’", "'")
                if not rx.match(w):
                    continue
                yield topic, age, diff, w


def core_map():
    """word -> {"age": min age, "diff": min difficulty, "topics": [ids in CORE order]}."""
    out = {}
    for topic, age, diff, w in iter_core():
        rec = out.get(w)
        if rec is None:
            out[w] = {"age": age, "diff": diff, "topics": [topic]}
        else:
            rec["age"] = min(rec["age"], age)
            rec["diff"] = min(rec["diff"], diff)
            if topic != "traits" and topic not in rec["topics"]:
                rec["topics"].insert(0, topic)     # specific topic outranks generic
            elif topic == "traits" and topic not in rec["topics"]:
                rec["topics"].append(topic)
    return out


def core_stats():
    from collections import Counter
    c, ages, diffs = Counter(), Counter(), Counter()
    m = core_map()
    for w, r in m.items():
        for t in r["topics"]:
            c[t] += 1
        ages[r["age"]] += 1
        diffs[r["diff"]] += 1
    return {"total_words": len(m), "total_topic_links": sum(c.values()),
            "by_topic": dict(c.most_common()),
            "by_age": dict(sorted(ages.items())),
            "by_diff": dict(sorted(diffs.items()))}


if __name__ == "__main__":
    import json
    print(json.dumps(core_stats(), ensure_ascii=False, indent=1))
